def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    for name, topic in TOPICS.items():
        body = VERIFIED + str(topic["body"])
        globs = [str(g) for g in topic["globs"]]  # type: ignore[attr-defined]
        always = bool(topic.get("always", False))

        # Claude Code: path-scoped rules; a file without `paths` is always loaded.
        claude_head = (
            "" if always else "---\npaths:\n" + "".join(f'  - "{g}"\n' for g in globs) + "---\n\n"
        )
        write(ROOT / ".claude" / "rules" / f"{name}.md", claude_head + body)

        # GitHub Copilot: comma-separated globs in `applyTo`.
        write(
            ROOT / ".github" / "instructions" / f"{name}.instructions.md",
            f'---\napplyTo: "{",".join(globs)}"\n---\n\n' + body,
        )

        # Kiro: always-on, or matched by a single pattern.
        pattern = globs[0] if len(globs) == 1 else "{" + ",".join(globs) + "}"
        kiro_head = (
            "---\ninclusion: always\n---\n\n"
            if always
            else f'---\ninclusion: fileMatch\nfileMatchPattern: "{pattern}"\n---\n\n'
        )
        write(ROOT / ".kiro" / "steering" / f"{name}.md", kiro_head + body)


if __name__ == "__main__":
    main()
